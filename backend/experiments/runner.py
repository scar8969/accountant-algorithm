def build_synthetic(cfg: dict) -> tuple[list[dict], list[dict]]:
    sc = cfg["synthetic"]
    profiles = generate_profiles(sc["n_profiles"], seed=cfg["seed"],
                                 missing_rate=sc.get("missing_rate", 0.10))
    pairs = simulate_pairs(profiles, seed=cfg["seed"], exposure_k=sc["exposure_k"])
    return profiles, pairs


def make_rows(pairs: list[dict]) -> list[dict]:
    """Both orderings of every pair, so directional models see both sides."""
    rows: list[dict] = []
    for p in pairs:
        rows.append({
            "a": p["a"], "b": p["b"], "interest_a": p["interest_a"],
            "mutual": p["mutual"], "quality_a": p["quality_a"],
            "direction": 0, "ts": p["ts_a"], "pair": p,
        })
        rows.append({
            "a": p["b"], "b": p["a"], "interest_a": p["interest_b"],
            "mutual": p["mutual"], "quality_a": p["quality_b"],
            "direction": 1, "ts": p["ts_b"], "pair": p,
        })
    return rows


def pair_rows(pairs: list[dict]) -> list[dict]:
    """One row per unordered pair.

    Mutual interest and interaction quality are pair-level outcomes. Building them
    from both orderings would duplicate every observation, halve the apparent
    variance and inflate the positive count, so those tasks use this single row.
    """
    return [{"a": p["a"], "b": p["b"], "interest_a": p["interest_a"],
             "mutual": p["mutual"], "quality_a": p["quality_a"], "pair": p}
            for p in pairs]


def _rows_for(rows: list[dict], task: str) -> list[dict]:
    if task == "directional":
        return [r for r in rows if r["interest_a"] is not None]
    if task == "mutual":
        return [r for r in rows if r["mutual"] is not None]
    if task == "interaction":
        return [r for r in rows if r["quality_a"] is not None]
    raise ValueError(task)


def rows_for_task(pairs: list[dict], task: str) -> list[dict]:
    """Task-appropriate rows: both directions for A, one row per pair for B and C."""
    if task == "directional":
        return _rows_for(make_rows(pairs), task)
    return _rows_for(pair_rows(pairs), task)


# --------------------------------------------------------------------------- #
# metric helpers
# --------------------------------------------------------------------------- #
def _score_array(rows: list[dict], model: TaskModel, task: str) -> np.ndarray:
    """Model scores as floats. Unscored pairs are pushed to the bottom."""
    raw = [model.score(r, task) for r in rows]
    known = [s for s in raw if s is not None]
    floor = (min(known) - 1.0) if known else -1.0
    return np.array([floor if s is None else float(s) for s in raw], dtype=float)


def _prob_array(rows: list[dict], model: TaskModel, task: str) -> np.ndarray | None:
    if not model.outputs_probability:
        return None
    vals = [model.probability(r, task) for r in rows]
    if any(v is None for v in vals):
        return None
    return np.array([float(v) for v in vals], dtype=float)


def _labels(rows: list[dict], task: str) -> np.ndarray:
    if task == "directional":
        return np.array([1.0 if r["interest_a"] else 0.0 for r in rows])
    if task == "mutual":
        return np.array([1.0 if r["mutual"] else 0.0 for r in rows])
    return np.array([float(r["quality_a"]) for r in rows], dtype=float)


def _rank_block(rows: list[dict], model: TaskModel, task: str, k: int,
                candidate_map: dict[str, list[dict]]) -> dict:
    ranked: list[list[tuple[float, float]]] = []
    divs: list[float] = []
    scored = total = 0
    for query_id, items in candidate_map.items():
        scored_items = []
        for item in items:
            row = {"a": item["query"], "b": item["candidate"]}
            if task == "mutual":
                relevance = item.get("mutual")
            else:
                relevance = item.get("interest")
            if relevance is None:
                continue
            s = model.score(row, task)
            scored += s is not None
            total += 1
            scored_items.append((float(s) if s is not None else float("-inf"),
                                 float(relevance), item["candidate"]))
        if len(scored_items) >= 2:
            ranked.append([(s, rel) for s, rel, _ in scored_items])
            top = [cand for _, _, cand in sorted(scored_items, key=lambda t: -t[0])][:k]
            divs.append(rk.diversity_at_k(top, "goal", items[0]["query"].get("goal"), k))
    block = rk.evaluate_rankings(ranked, k)
    block["coverage"] = round(scored / total, 4) if total else 0.0
    block["diversity"] = round(float(np.mean(divs)), 4) if divs else None
    return block


def _bootstrap_ci(rows: list[dict], scores: np.ndarray, task: str, seed: int,
                  iters: int) -> dict:
    groups = [r["a"]["participant_id"] for r in rows]
    items = [{"y": float(y), "s": float(s)} for y, s in zip(_labels(rows, task), scores)]

    def metric(sample):
        y = np.array([i["y"] for i in sample])
        s = np.array([i["s"] for i in sample])
        return cls.pr_auc(y, s)

    return cluster_bootstrap(items, groups, metric, iters=iters, seed=seed)


# --------------------------------------------------------------------------- #
# one split
# --------------------------------------------------------------------------- #
def evaluate_split(train_pairs: list[dict], test_pairs: list[dict], cfg: dict,
                   *,
                   models: dict[str, list[str]] | None = None,
                   embed=None,
                   tasks: tuple[str, ...] = ("directional", "mutual", "interaction")) -> dict:
    embed = embed or get_default_provider()
    models = models or cfg["models"]
    protocol = cfg["protocol"]
    k = protocol["k"]
    iters = protocol["bootstrap_iters"]
    bins = protocol["bins"]
    seed = cfg["seed"]

    cand_map = candidate_sets(test_pairs)

    out: dict = {"tasks": {}, "per_model": {}, "dataset": {
        "train_pairs": len(train_pairs), "test_pairs": len(test_pairs),
        "train_rows": len(make_rows(train_pairs)),
        "test_rows": len(make_rows(test_pairs)),
    }}

    for task in tasks:
        train_rows = rows_for_task(train_pairs, task)
        test_rows = rows_for_task(test_pairs, task)
        out["dataset"][f"n_train_{task}"] = len(train_rows)
        out["dataset"][f"n_test_{task}"] = len(test_rows)
        if not train_rows or not test_rows:
            continue

        y = _labels(test_rows, task) if task != "interaction" else None
        task_models: dict[str, dict] = {}

        for name in models.get(task, []):
            model = build_model(name, seed=seed, embed=embed)
            model.fit(train_rows, task)
            payload: dict = {"config": model.get_config()}

            if task == "interaction":
                preds = [model.score(r, task) for r in test_rows]
                actual = np.array([float(r["quality_a"]) for r in test_rows])
                ok = np.array([p is not None for p in preds])
                if ok.any():
                    p = np.array([float(v) if v is not None else np.nan for v in preds])
                    mask = ~np.isnan(p)
                    err = p[mask] - actual[mask]
                    payload["metrics"] = {
                        "n": int(mask.sum()),
                        "mae": round(float(np.mean(np.abs(err))), 4),
                        "rmse": round(float(np.sqrt(np.mean(err ** 2))), 4),
                        "mean_pred": round(float(np.mean(p[mask])), 4),
                        "mean_actual": round(float(np.mean(actual[mask])), 4),
                    }
                task_models[name] = payload
                continue

            scores = _score_array(test_rows, model, task)
            probs = _prob_array(test_rows, model, task)
            metrics = cls.summarise(y, probs, scores=scores, bins=bins)
            metrics["ci"] = _bootstrap_ci(test_rows, scores, task, seed, iters)
            if probs is not None:
                metrics["calibration"] = calib.calibration_block(y, probs, bins)
            payload["metrics"] = metrics
            payload["ranking"] = _rank_block(test_rows, model, task, k, cand_map)
            task_models[name] = payload

        out["tasks"][task] = task_models

    return out


# --------------------------------------------------------------------------- #
# headline comparison
# --------------------------------------------------------------------------- #
def _compare(task_results: dict, task: str, cfg: dict) -> dict:
    models = task_results.get(task, {})
    if not models:
        return {}
    metric = cfg["primary_metric"]

    def value(name):
        m = models.get(name, {}).get("metrics", {})
        return m.get(metric)

    ordered = sorted(
        ((name, value(name)) for name in models),
        key=lambda kv: (-1 if kv[1] is None else kv[1]), reverse=True)
    best_name, best_value = next(((n, v) for n, v in ordered if v is not None),
                                 (None, None))
    random_v = value("random")
    structured_v = value("structured")
    return {
        "primary_metric": metric,
        "ranking": [{"model": n, "value": v} for n, v in ordered],
        "best_model": best_name,
        "best_value": best_value,
        "delta_vs_random": None if (best_value is None or random_v is None)
        else round(best_value - random_v, 4),
        "delta_vs_structured": None if (best_value is None or structured_v is None)
        else round(best_value - structured_v, 4),
        "ci": models.get(best_name, {}).get("metrics", {}).get("ci") if best_name else None,
        "ci_width": _ci_width(models.get(best_name, {}).get("metrics", {}).get("ci")),
    }


def _ci_width(ci: dict | None) -> float | None:
    if not ci or ci.get("lo") is None or ci.get("hi") is None:
        return None
    return round(float(ci["hi"]) - float(ci["lo"]), 4)


def _failure_cases(eval_main: dict, test_pairs: list[dict], limit: int = 8) -> list[dict]:
    """High-score misses and low-score hits for the structured score.

    These are deliberately the *structured* model's errors (so each case can be
    explained feature by feature), even though the run's best model may be a
    learned one. The `scored_by` field says so.
    """
    mutual = eval_main["tasks"].get("mutual", {})
    if not mutual:
        return []
    best = min(
        (n for n, p in mutual.items() if p.get("metrics", {}).get("ci", {}).get("estimate")
         is not None),
        key=lambda n: -mutual[n]["metrics"]["ci"]["estimate"], default=None)
    if best is None:
        return []
    cases = []
    for pair in test_pairs:
        if pair.get("mutual") is None:
            continue
        ps = score_pair(pair["a"], pair["b"])
        exp = explanation(ps, top=3)
        cases.append({
            "pair": [pair["a"]["participant_id"], pair["b"]["participant_id"]],
            "observed_mutual": pair["mutual"],
            "structured_score": ps.score,
            "coverage": ps.coverage,
            "gate_a": ps.gate_a, "gate_b": ps.gate_b,
            "top_positive": exp["contributions"],
            "top_conflict": exp["conflicts"],
            "missing": exp["missing"],
            "scored_by": "structured",
            "best_model_in_run": best,
        })
    false_positives = [c for c in cases if c["observed_mutual"] is False
                       and (c["structured_score"] or 0) >= 60]
    false_negatives = [c for c in cases if c["observed_mutual"] is True
                       and (c["structured_score"] or 0) < 40]
    false_positives.sort(key=lambda c: -(c["structured_score"] or 0))
    false_negatives.sort(key=lambda c: (c["structured_score"] or 0))
    return (false_positives[:limit] + false_negatives[:limit])


def _power_note(task_results: dict, counts: dict) -> dict:
    """Plain-language precision statement for the primary task."""
    mutual = task_results.get("mutual") or {}
    scored = [(name, payload["metrics"]["pr_auc"], payload["metrics"].get("ci") or {})
              for name, payload in mutual.items()
              if payload.get("metrics", {}).get("pr_auc") is not None]
    if not scored:
        return {"statement": "No mutual-interest model produced a score."}
    name, value, ci = max(scored, key=lambda row: row[1])
    width = _ci_width(ci)
    positives = counts.get("mutual_positives", 0)
    statement = (
        f"With {positives} positive mutual outcomes in the held-out split, the 95% "
        f"interval for the best model ({name}) spans {width:.2f} PR-AUC."
        if width is not None else
        f"With {positives} positive mutual outcomes the interval could not be computed.")
    return {
        "best_model": name,
        "best_pr_auc": round(value, 4),
        "ci_width": width,
        "mutual_positives": positives,
        "statement": statement + " Differences smaller than that width are "
                                "indistinguishable in this sample.",
    }


# --------------------------------------------------------------------------- #
# entry point
# --------------------------------------------------------------------------- #
def run_experiment(cfg: dict, out_dir: str | Path | None = None,
                   write_artifacts: bool = True) -> dict:
    validate_config(cfg)
    created = datetime.now(timezone.utc).isoformat()
    seed = cfg["seed"]
    embed = get_default_provider()

    profiles, pairs = build_synthetic(cfg)
    train_pairs, test_pairs, dropped = grouped_pair_split(
        pairs, test_frac=cfg["protocol"]["test_frac"], seed=seed)
    assert_no_leakage(train_pairs, test_pairs)

    main = evaluate_split(train_pairs, test_pairs, cfg, embed=embed)

    temporal_models = {
        task: [m for m in names if m in ("random", "structured", "text",
                                         "directional_logistic",
                                         "mutual_independence", "mutual_logistic")]
        for task, names in cfg["models"].items()
    }
    t_train, t_test = temporal_pair_split(pairs, cfg["protocol"]["temporal_train_frac"])
    assert_temporal_order(t_train, t_test)
    temporal = evaluate_split(t_train, t_test, cfg, models=temporal_models, embed=embed)

    directional_rows = rows_for_task(test_pairs, "directional")
    mutual_rows = rows_for_task(test_pairs, "mutual")
    interaction_rows = rows_for_task(test_pairs, "interaction")

    d_pos = sum(1 for r in directional_rows if r["interest_a"])
    m_pos = sum(1 for r in mutual_rows if r["mutual"])
    i_pos = sum(1 for r in interaction_rows if (r["quality_a"] or 0) >= 4)

    results = {
        "experiment": {
            "name": cfg["name"],
            "hypothesis": cfg["hypothesis"],
            "primary_metric": cfg["primary_metric"],
            "created_at": created,
            "config_hash": _config_hash(cfg),
            "code_revision": _code_revision(),
            "feature_schema_version": S.FEATURE_SCHEMA_VERSION,
            "simulation_version": SIMULATION_VERSION,
            "python": platform.python_version(),
            "seed": seed,
            "config": cfg,
        },
        "simulation": simulation_manifest(),
        "dataset": {
            "kind": "synthetic",
            "version": f"synthetic-{SIMULATION_VERSION}-n{cfg['synthetic']['n_profiles']}"
                       f"-seed{seed}",
            "n_profiles": len(profiles),
            "n_pairs": len(pairs),
            "n_directional_observations": sum(
                1 for r in make_rows(pairs) if r["interest_a"] is not None),
            "n_mutual_observations": sum(1 for p in pairs if p["mutual"] is not None),
            "n_interaction_observations": sum(1 for p in pairs if p["quality_a"] is not None),
            "unknown_interest_directions": sum(
                1 for p in pairs for v in (p["interest_a"], p["interest_b"]) if v is None),
            "test_positives": {"directional": d_pos, "mutual": m_pos,
                               "interaction_good": i_pos},
        },
        "protocol": {
            "primary": "participant_grouped (unseen people)",
            "test_frac": cfg["protocol"]["test_frac"],
            "seed": seed,
            "k": cfg["protocol"]["k"],
            "bootstrap_iters": cfg["protocol"]["bootstrap_iters"],
            "leakage": leakage_report(train_pairs, test_pairs),
            "dropped_straddling_pairs": len(dropped),
            "temporal": {
                "protocol": "temporal (known people, later observations)",
                "participants_may_overlap": True,
                "train_frac": cfg["protocol"]["temporal_train_frac"],
                "dataset": temporal["dataset"],
                "leakage": leakage_report(t_train, t_test),
                "ordering_verified": True,
                "results": temporal["tasks"],
            },
        },
        "results": main["tasks"],
        "comparison": {task: _compare(main["tasks"], task, cfg)
                       for task in ("directional", "mutual", "interaction")},
        "failure_cases": _failure_cases(main, test_pairs),
        "power_note": _power_note(main["tasks"], {
            "mutual_positives": m_pos, "directional_positives": d_pos}),
        "limitations": cfg["limitations"],
    }

    if write_artifacts:
        path = Path(out_dir) if out_dir else RESULTS_DIR
        path.mkdir(parents=True, exist_ok=True)
        (path / "results.json").write_text(json.dumps(results, indent=2, default=str),
                                           encoding="utf-8")
        (path / "results.csv").write_text(_to_csv(results), encoding="utf-8")
    return results


def _to_csv(results: dict) -> str:
    rows = ["task,model,metric,value,ci_lo,ci_hi"]
    for task, models in results["results"].items():
        for name, payload in models.items():
            metrics = payload.get("metrics", {})
            ci = metrics.get("ci", {}) or {}
            for key in ("n", "positives", "prevalence", "pr_auc", "roc_auc",
                        "log_loss", "brier", "ece", "mae", "rmse"):
                if key in metrics and metrics[key] is not None:
                    lo = ci.get("lo") if key == results["experiment"]["primary_metric"] else ""
                    hi = ci.get("hi") if key == results["experiment"]["primary_metric"] else ""
                    rows.append(f"{task},{name},{key},{metrics[key]},{lo or ''},{hi or ''}")
            ranking = payload.get("ranking", {})
            for key in ("ndcg@5", "recall@5", "mrr", "coverage", "diversity"):
                if ranking.get(key) is not None:
                    rows.append(f"{task}_ranking,{name},{key},{ranking[key]},,")
    return "\n".join(rows) + "\n"
